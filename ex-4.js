// Switch Statement
let lightBulbStatus = "On";

//Start coding here

switch (lightBulbStatus) {
    case "On":
        console.log("the light bulb status is on");
    break;

    case "Off":
        console.log("the light bulb is off");
    break;

    default:
        console.log("the light bulb is broken");
}